/**
 * UseCase1BookMyStayApp
 *
 * This class represents the entry point for the BookMyStay Hotel Booking application.
 * It demonstrates how a Java program starts execution using the main() method
 * and prints a welcome message to the console.
 *
 * The application displays the application name and version information
 * when it starts.
 *
 * @author Aksh Garg
 * @version 1.0
 */
public class UseCase1BookMyStayApp {

    /**
     * Entry point of the Java application.
     * The JVM invokes this method when the program starts.
     *
     * @param args command line arguments
     */
    public static void main(String[] args) {

        // Print welcome message
        System.out.println("===================================");
        System.out.println(" Welcome to BookMyStay");
        System.out.println(" Hotel Booking System v1.0");
        System.out.println("===================================");
        System.out.println("Application started successfully.");

    }
}